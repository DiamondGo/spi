const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path')
module.exports = async function({app, waitFor, pass, fill, artifacts, hashes, before}) {
  const evaluate = expression => app.eval(expression)
  const nextVersion = require('../package.json').version.replace(/\d+$/, patch => String(Number(patch) + 1))
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const phase = expected => waitFor(() => evaluate(`document.querySelector('[data-update-phase]')?.dataset.updatePhase === ${JSON.stringify(expected)}`), 'update phase ' + expected, 45000)
  const capture = async name => { const shot = await app.send('Page.captureScreenshot', {format:'png'}); fs.writeFileSync(path.join(artifacts, name+'.png'), Buffer.from(shot.data,'base64')) }
  const changeMode = value => fs.writeFileSync(path.join(artifacts,'update-mode.txt'), value)
  await fill(app, 'SPI_UPDATE_DRAFT_MUST_SURVIVE')
  await click('.app-settings-button')
  await waitFor(() => evaluate(`document.querySelector('.app-settings-dialog')?.open && !!document.querySelector('[data-update-phase]')`), 'update controls in settings')
  assert.equal(await evaluate(`!!document.querySelector('#remote-settings-content')`),false,'checking updates must not mount OS credential probes')
  const initial = await evaluate('window.spi.getAppUpdate()')
  assert.equal(initial.currentVersion, require('../package.json').version)
  assert.equal(initial.target, process.platform+'-'+process.arch)
  assert.ok(initial.installRoot && initial.phase)
  assert.ok(await evaluate(`document.querySelector('.app-update-details').innerText.includes('npm')`))
  await capture('updates-settings')
  pass('preload + main updater available in real runtime; version/architecture and GitHub-only installation location visible', initial)

  // Installed/native binaries ignore test helper overrides; never actually update the test runner.
  if (process.env.SPI_SMOKE_EXECUTABLE) {
    await waitFor(() => evaluate(`document.querySelector('[data-update-action="check"]') && !document.querySelector('[data-update-action="check"]').disabled`), 'native metadata request settles', 180000)
    const nativeState = await evaluate('window.spi.getAppUpdate()')
    assert.ok(['current', 'available'].includes(nativeState.phase), JSON.stringify(nativeState))
    await click('.settings-close')
    assert.equal(await evaluate(`document.querySelector('.input-bar textarea').value`), 'SPI_UPDATE_DRAFT_MUST_SURVIVE')
    pass('extracted native runtime loads bundled installer without modifying the running app or draft', nativeState)
    assert.equal(app.errors.length,0,JSON.stringify(app.errors)); return
  }

  await click('[data-update-action="check"]'); await phase('current')
  assert.equal(await evaluate(`!!document.querySelector('.app-update-notice')`), false)
  pass('current version has no false-positive exclamation mark')
  changeMode('offline'); await click('[data-update-action="check"]'); await phase('error')
  assert.ok(await evaluate(`document.querySelector('.app-update-details [role="alert"]').textContent.includes('SPI_UPDATE_OFFLINE')`))
  assert.equal(await evaluate(`!!document.querySelector('.app-update-notice')`), false)
  changeMode('available'); await click('[data-update-action="check"]'); await phase('available')
  await click('.settings-close')
  await waitFor(() => evaluate(`document.querySelector('.app-update-notice')?.textContent === '!'`), 'new-version exclamation')
  const geometry = await evaluate(`(()=>{const a=document.querySelector('.app-update-notice').getBoundingClientRect(), b=document.querySelector('.app-settings-button').getBoundingClientRect();return {right:a.right,left:b.left,region:getComputedStyle(document.querySelector('.app-update-notice').parentElement).webkitAppRegion}})()`)
  assert.ok(geometry.right <= geometry.left); assert.ok(geometry.left-geometry.right < 40)
  await capture('updates-notice')
  await click('.app-update-notice'); await phase('available')
  assert.ok(await evaluate(`document.querySelector('.app-update-details').innerText.includes(${JSON.stringify(nextVersion)})`))
  pass('offline retry recovers; accessible clickable ! sits next to gear and opens new-version details')

  changeMode('unsupported'); await click('[data-update-action="check"]'); await phase('available')
  assert.equal(await evaluate(`!!document.querySelector('[data-update-action="install"]')`), false)
  changeMode('available'); await click('[data-update-action="check"]'); await phase('available')
  changeMode('install-failure'); await click('[data-update-action="install"]'); await phase('error')
  assert.ok(await evaluate(`document.querySelector('.app-update-details [role="alert"]').textContent.includes('SPI_UPDATE_CHECKSUM_MISMATCH')`))
  assert.equal(await evaluate(`!!document.querySelector('[data-update-action="restart"]')`), false)
  changeMode('available'); await click('[data-update-action="install"]'); await phase('ready')
  assert.ok(await evaluate(`!!document.querySelector('[data-update-action="restart"]')`))
  assert.ok(await evaluate(`document.querySelector('[data-update-action="check"]').disabled`))
  assert.equal(await evaluate(`document.querySelector('.input-bar textarea').value`), 'SPI_UPDATE_DRAFT_MUST_SURVIVE')
  pass('unsupported target cannot install; failed verification cannot restart; explicit retry reaches restart-ready without interrupting draft')

  for (const theme of ['dark','light','high-contrast']) for (const language of ['en','zh']) {
    await evaluate(`window.spi.updateAppSettings({theme:${JSON.stringify(theme)},language:${JSON.stringify(language)}})`)
    await waitFor(() => evaluate(`document.documentElement.dataset.theme===${JSON.stringify(theme)} && document.documentElement.lang===${JSON.stringify(language==='zh'?'zh-CN':'en')}`), 'update language/theme')
    await app.send('Emulation.setDeviceMetricsOverride',{width:900,height:640,deviceScaleFactor:1,mobile:false})
    const bounds = await evaluate(`(()=>{const e=document.querySelector('.app-settings-dialog').getBoundingClientRect();return {left:e.left,right:e.right,top:e.top,bottom:e.bottom,overflow:document.documentElement.scrollWidth>innerWidth}})()`)
    assert.ok(bounds.left>=0 && bounds.right<=900 && bounds.top>=0 && bounds.bottom<=640,JSON.stringify(bounds)); assert.equal(bounds.overflow,false)
    const label = await evaluate(`document.querySelector('[data-update-action="restart"]').textContent`)
    assert.equal(label,language==='zh'?'重启生效':'Restart to apply')
    await capture(`updates-ready-${theme}-${language}`)
    await app.send('Emulation.clearDeviceMetricsOverride')
  }
  await click('.settings-close')
  assert.equal(await evaluate(`document.querySelector('.input-bar textarea').value`),'SPI_UPDATE_DRAFT_MUST_SURVIVE')
  assert.deepEqual(hashes(),before); assert.equal(app.errors.length,0,JSON.stringify(app.errors))
  pass('update states readable in six theme/language combinations at 900px; profile and drafts unchanged; no renderer errors')
}
