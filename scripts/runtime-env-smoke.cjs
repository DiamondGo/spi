// Real packaged GUI + real Pi, with no Node on the GUI's PATH; login shell supplies it.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
module.exports=async({app,workspace,waitFor,pass,hashes,before,artifacts,launch,stop,launchOptions})=>{
  const open=await app.eval(`window.spi.openSession({cwd:${JSON.stringify(workspace)}})`)
  assert.ok(open.sessionId);assert.ok(open.state.sessionFile)
  pass('new session opens with no Node on desktop PATH; Pi launcher and login-selected Node are preserved')
  const prompt='Read the private fixture '+JSON.stringify({tool:'read',input:{path:path.join(workspace,'smoke.txt')}})
  await app.eval(`window.spi.sendPrompt(${JSON.stringify(open.sessionId)},${JSON.stringify(prompt)},'normal')`)
  await waitFor(()=>app.eval(`window.spi.getMessages(${JSON.stringify(open.sessionId)}).then(m=>JSON.stringify(m).includes('SPI_FIXTURE_DONE'))`),'private loopback reply with desktop Node absent')
  const history=await app.eval(`window.spi.getMessages(${JSON.stringify(open.sessionId)})`)
  assert.ok(history.length>1);assert.ok(fs.existsSync(open.state.sessionFile))
  pass('actual real-Pi read/model roundtrip succeeds without modifying Pi/model/auth configuration')
  await app.eval(`window.spi.closeSession(${JSON.stringify(open.sessionId)})`)
  await waitFor(()=>app.eval(`window.spi.getYoloState().then(s=>!s.sessions[${JSON.stringify(open.sessionId)}])`),'closed Pi process retired before history reopen')
  const reopened=await app.eval(`window.spi.openSession({cwd:${JSON.stringify(workspace)},sessionPath:${JSON.stringify(open.state.sessionFile)}})`)
  assert.notEqual(reopened.sessionId,open.sessionId)
  const restored=await app.eval(`window.spi.getMessages(${JSON.stringify(reopened.sessionId)})`)
  assert.ok(JSON.stringify(restored).includes('SPI_FIXTURE_DONE'))
  pass('saved history session reopens with its messages under the same sparse desktop environment')
  await app.eval(`window.spi.closeSession(${JSON.stringify(reopened.sessionId)})`)
  const fresh=await app.eval(`window.spi.openSession({cwd:${JSON.stringify(workspace)}})`)
  assert.ok(fresh.sessionId);assert.notEqual(fresh.state.sessionFile,open.state.sessionFile)
  pass('another fresh session can open after close; startup failures cannot poison later opens')
  const node=path.join(artifacts,'login-node-bin/node'),shell=path.join(artifacts,'login-shell')
  const originalShell=fs.readFileSync(shell)
  await app.eval(`document.querySelector('.app-settings-button').click()`)
  await waitFor(()=>app.eval(`!!document.querySelector('.node-settings')&&!document.querySelector('.node-settings').disabled`),'manual Node setting loaded')
  const input=async value=>{await app.eval(`(()=>{const e=document.querySelector('[data-setting="nodePath"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}))})()`);await waitFor(()=>app.eval(`!document.querySelector('[data-action="save-node"]').disabled`),'manual Node save enabled')}
  await input('/fixture/missing-node');await app.eval(`document.querySelector('[data-action="save-node"]').click()`)
  await waitFor(()=>app.eval(`document.querySelector('.node-settings .settings-error')?.textContent.includes('Configured Node.js')`),'invalid Node path feedback')
  assert.equal(await app.eval('window.spi.getNodePath()'),null)
  pass('Settings rejects invalid Node executables without overwriting the saved automatic choice')
  await input(node);await app.eval(`document.querySelector('[data-action="save-node"]').click()`)
  await waitFor(()=>app.eval(`window.spi.getNodePath().then(p=>p===${JSON.stringify(node)})`),'manual Node path saved')
  await app.eval(`document.querySelector('.settings-close').click()`)
  fs.writeFileSync(shell,'#!/bin/sh\nexit 1\n')
  const manual=await app.eval(`window.spi.openSession({cwd:${JSON.stringify(workspace)}})`)
  assert.ok(manual.sessionId);assert.ok(await app.eval(`window.spi.getState(${JSON.stringify(fresh.sessionId)})`))
  pass('manual Node starts new sessions when automatic/login-shell detection is unavailable; existing sessions stay alive')
  fs.unlinkSync(node)
  const failure=await app.eval(`window.spi.openSession({cwd:${JSON.stringify(workspace)}}).then(()=>null,e=>e.message)`)
  assert.ok(failure.includes('Configured Node.js'));assert.ok(await app.eval(`window.spi.getState(${JSON.stringify(manual.sessionId)})`))
  fs.symlinkSync(process.execPath,node)
  pass('a removed saved Node fails explicitly, never silently falls back or kills an already-running session')
  let restarted
  try{
    await stop(app);restarted=await launch(launchOptions)
    assert.equal(await restarted.eval('window.spi.getNodePath()'),node)
    const saved=await restarted.eval(`window.spi.openSession({cwd:${JSON.stringify(workspace)},sessionPath:${JSON.stringify(open.state.sessionFile)}})`)
    assert.ok((await restarted.eval(`window.spi.getMessages(${JSON.stringify(saved.sessionId)})`)).length>1)
    pass('manual Node persists across app restart and saved history reopens even with login detection unavailable')
    fs.writeFileSync(shell,originalShell)
    await restarted.eval(`document.querySelector('.app-settings-button').click()`)
    await waitFor(()=>restarted.eval(`!!document.querySelector('.node-settings')&&!document.querySelector('.node-settings').disabled`),'persisted Node settings loaded')
    await restarted.eval(`document.querySelector('[data-action="auto-node"]').click()`)
    await waitFor(()=>restarted.eval(`window.spi.getNodePath().then(p=>p===null)`),'cleared manual Node')
    assert.ok(await restarted.eval(`window.spi.openSession({cwd:${JSON.stringify(workspace)}})`))
    pass('Settings can clear the override and return new sessions to automatic login-shell detection')
  }finally{await stop(restarted);fs.writeFileSync(shell,originalShell)}
  assert.deepEqual(hashes(),before)
}
